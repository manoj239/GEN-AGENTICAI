class PlanStep(BaseModel):
    """A single step in the VM remediation plan."""
    step_number: int = Field(description="1-based step index")
    agent: str = Field(description="Name of the agent that runs this step")
    action: str = Field(description="Short imperative action, e.g. 'Ping VM and test SSH port 22'")
    rationale: str = Field(description="Why this step is required for the incident")


class ExecutionPlan(BaseModel):
    """Structured execution plan produced by the PlannerAgent LLM."""
    incident_summary: str = Field(description="One-sentence summary of the incident")
    steps: list[PlanStep] = Field(description="Ordered list of 5-7 diagnostic + remediation steps")
    estimated_risk: Literal["low", "medium", "high"] = Field(
        description="Risk of the proposed remediation to production traffic"
    )


class DiagnosticAnalysis(BaseModel):
    """Structured post-diagnostic analysis produced before human approval."""
    overall_health: Literal["healthy", "degraded", "critical"] = Field(
        description="Overall VM health rollup"
    )
    root_cause: str = Field(description="Most likely root cause of the incident")
    key_findings: list[str] = Field(description="Bullet points summarising each health check")
    recommendation: Literal["restart", "investigate_further", "no_action"] = Field(
        description="Recommended next action for the operator"
    )
    confidence: float = Field(ge=0.0, le=1.0, description="Confidence in the recommendation (0-1)")
    reasoning: str = Field(description="Short justification for the recommendation")


class InvestigationReport(BaseModel):
    """Enterprise ServiceNow-style investigation report composed from workflow findings."""
    incident_summary: str = Field(description="One-paragraph summary of the incident as observed")
    ci_details: list[str] = Field(description="Configuration Item details (host, IP, OS, environment, service offering, etc.)")
    connectivity_findings: list[str] = Field(description="Reachability / SSH / ping observations")
    cpu_findings: list[str] = Field(description="Observed CPU utilization and threshold status")
    memory_findings: list[str] = Field(description="Observed memory utilization and threshold status")
    disk_findings: list[str] = Field(description="Observed filesystem utilization per mount")
    process_findings: list[str] = Field(description="Observed service/process state, PID and active status")
    root_cause_analysis: str = Field(description="Root cause derived strictly from the collected findings")


class AgentNarrative(BaseModel):
    """Enterprise-style investigation narrative generated by LLM."""
    summary: list[str] = Field(description="4-10 concise bullet-point investigation findings")

