def log_event(agent_name: str, task: str, description: str, output: dict, formatted_output: str = "", status: str = "completed"):
    """Log agent event to backend API and (if active) push to live SSE queue.
    
    Args:
        agent_name: Name of the agent
        task: Task description
        description: Detailed description of what the agent did
        output: Raw JSON output dict (kept for backward compatibility and audit)
        formatted_output: Human-readable summary (auto-generated via LLM if empty)
        status: Event status
    """
    # Auto-generate formatted_output via LLM if not provided
    if not formatted_output:
        formatted_output = build_agent_summary(agent_name, description, output)
    print("\n" + "=" * 60)
    print(f"AGENT: {agent_name}")
    print("FORMATTED OUTPUT:")
    print(formatted_output)
    print("=" * 60 + "\n")
    payload = {
        "agent": agent_name,
        "task": task,
        "description": description,
        "output": json.dumps(output) if isinstance(output, dict) else str(output),
        "formatted_output": formatted_output,
        "status": status,
        "timestamp": datetime.now().isoformat()
    }

    # Push to live streaming queue (if a workflow was triggered via the
    # /run_vm_stabilizer_stream_live endpoint)
    if _live_queue is not None:
        try:
            _live_queue.put({"type": "live_output", "content": payload})
        except Exception as e:
            print(f"  [Warning] Failed to push to live queue: {e}")

    # Also POST to the backend event log (keeps /api/agents/event-stream working)
    try:
        requests.post(f"{API_URL}/api/agents/event", json=payload, timeout=5)
    except Exception as e:
        print(f"  [Warning] Failed to log event: {e}")

